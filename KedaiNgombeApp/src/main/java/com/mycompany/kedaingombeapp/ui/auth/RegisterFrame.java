    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        boolean ok = authService.register(namaRegisterForm.getText().trim(),
                                          emailRegisterForm.getText().trim(),
                                          new String(passwordRegisterForm.getPassword()));
        if (!ok) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Gagal daftar: cek format email, password minimal 8 karakter, atau email sudah terdaftar");
            return;
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Registrasi berhasil, silakan login");
        new LoginFrame().setVisible(true);   // balik ke login
        dispose();
    }//GEN-LAST:event_btnRegisterActionPerformed

