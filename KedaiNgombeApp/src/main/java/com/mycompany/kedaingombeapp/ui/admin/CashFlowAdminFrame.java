    private void siapkanTabel() {
    tableModel = new DefaultTableModel(
        new Object[]{"ID", "Pembeli", "Total", "Bayar", "Kembalian", "Waktu"}, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    tblTransaksi.setModel(tableModel);
    }

    private void tampilkanLaporan(Date tanggal) {
        tableModel.setRowCount(0);
        List<Object[]> daftar = laporanService.daftarHarian(tanggal);
        for (Object[] baris : daftar) {
            tableModel.addRow(baris);
        }
        lblTotalHari.setText("Pendapatan hari ini: Rp " + laporanService.totalHarian(tanggal));
        lblTotalBulan.setText("Pendapatan bulan ini: Rp " + laporanService.totalBulanan(tanggal));
        lblJumlah.setText("Jumlah transaksi: " + daftar.size());
    }

