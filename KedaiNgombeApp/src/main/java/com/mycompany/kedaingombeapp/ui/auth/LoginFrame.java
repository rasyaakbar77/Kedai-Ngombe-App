    private void btnMasukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMasukActionPerformed
        // TODO add your handling code here:
        String email = emailLoginForm.getText().trim();
        String password = new String(passwordLoginFrom.getPassword());

        if (email.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Email dan password wajib diisi");
            return;
        }

        User user = authService.login(email, password);
        if (user == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Email atau password salah");
            return;
        }

        if ("admin".equals(user.getRole())) {
            new MenuAdminFrame(user).setVisible(true);
        } else {
            new MenuUserFrame(user).setVisible(true);
        }
        dispose();

    }//GEN-LAST:event_btnMasukActionPerformed

