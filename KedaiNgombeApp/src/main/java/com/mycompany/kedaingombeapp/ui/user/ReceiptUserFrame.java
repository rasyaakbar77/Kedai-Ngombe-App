    private void muatReceipt(int idTransaksi) {
        StringBuilder sb = new StringBuilder();
        String qHeader = "SELECT total_harga, bayar, kembalian, created_at FROM transactions WHERE id = ?";
        String qDetail = "SELECT p.nama_menu, d.jumlah, p.harga, d.subtotal "
                       + "FROM transactions_detail d JOIN products p ON d.product_id = p.id "
                       + "WHERE d.transactions_id = ?";

        try (Connection conn = DatabaseConnection.connect()) {
            sb.append("      KEDAI NGOMBE\n");
            sb.append("==============================\n");
            sb.append("No. Transaksi : ").append(idTransaksi).append("\n");

            try (PreparedStatement ps = conn.prepareStatement(qHeader)) {
                ps.setInt(1, idTransaksi);
                ResultSet rs = ps.executeQuery();
                if (rs.next()) {
                    sb.append("Tanggal       : ").append(rs.getTimestamp("created_at")).append("\n");
                    sb.append("Kasir/Pembeli : ").append(user.getNama()).append("\n");
                    sb.append("------------------------------\n");

                    try (PreparedStatement ps2 = conn.prepareStatement(qDetail)) {
                        ps2.setInt(1, idTransaksi);
                        ResultSet rd = ps2.executeQuery();
                        while (rd.next()) {
                            sb.append(rd.getString("nama_menu")).append("\n");
                            sb.append("  ").append(rd.getInt("jumlah")).append(" x ")
                              .append(rd.getInt("harga")).append(" = ")
                              .append(rd.getInt("subtotal")).append("\n");
                        }
                    }

                    sb.append("------------------------------\n");
                    sb.append("Total     : Rp ").append(rs.getInt("total_harga")).append("\n");
                    sb.append("Bayar     : Rp ").append(rs.getInt("bayar")).append("\n");
                    sb.append("Kembalian : Rp ").append(rs.getInt("kembalian")).append("\n");
                    sb.append("==============================\n");
                    sb.append("   Terima kasih!\n");
                }
            }
        } catch (SQLException e) {
            sb.append("Gagal memuat receipt: ").append(e.getMessage());
            e.printStackTrace();
        }

        txtReceipt.setText(sb.toString());
    }

