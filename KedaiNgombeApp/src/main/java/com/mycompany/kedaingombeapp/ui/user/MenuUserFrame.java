    private void tampilkanMenu(List<Menu> list) {
        jPanel1.removeAll();
        for (Menu m : list) {
            infoMenu.put(m.getId(), m);
            boolean dipilih = keranjang.containsKey(m.getId());
            int qty = dipilih ? keranjang.get(m.getId()) : 1;
            jPanel1.add(new MenuItemPanel(m, qty, dipilih, this::updateKeranjang));
        }
        jPanel1.revalidate();
        jPanel1.repaint();
    }
          
    private void updateKeranjang(MenuItemPanel card) {
        int id = card.getMenu().getId();
        if (card.isDipilih()) {
            keranjang.put(id, card.getQty());
        } else {
            keranjang.remove(id);
        }
        lblTotal.setText("Total: Rp " + hitungTotal());
    }

    private int hitungTotal() {
        int total = 0;
        for (Map.Entry<Integer, Integer> e : keranjang.entrySet()) {
            total += infoMenu.get(e.getKey()).getHarga() * e.getValue();
        }
        return total;
    }

