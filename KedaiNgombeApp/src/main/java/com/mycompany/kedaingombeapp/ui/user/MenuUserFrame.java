    private void btnCheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckoutActionPerformed
        // TODO add your handling code here:
        if (keranjang.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Keranjang masih kosong");
            return;
        }
        int total = hitungTotal();

        String input = JOptionPane.showInputDialog(this, "Total Rp " + total + "\nUang dibayar:");
        if (input == null) return;

        int bayar;
        try {
            bayar = Integer.parseInt(input.trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Masukkan angka yang valid");
            return;
        }
        if (bayar < total) {
            JOptionPane.showMessageDialog(this, "Uang kurang");
            return;
        }

        int idTransaksi = new TransaksiService().simpan(user.getId(), keranjang, infoMenu, bayar);
        if (idTransaksi < 0) {
            JOptionPane.showMessageDialog(this, "Transaksi gagal, stok mungkin tidak cukup");
            return;
        }

        new ReceiptUserFrame(user, idTransaksi).setVisible(true);
        dispose();
    }//GEN-LAST:event_btnCheckoutActionPerformed

    private void btnLogoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogoutActionPerformed
        // TODO add your handling code here:
        if (!keranjang.isEmpty()) {
            int konfirmasi = JOptionPane.showConfirmDialog(this,
                "Keranjang belum di-checkout dan akan hilang. Tetap logout?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);
            if (konfirmasi != JOptionPane.YES_OPTION) return;
        }
        new LoginFrame().setVisible(true);
        dispose();
        
    }//GEN-LAST:event_btnLogoutActionPerformed

