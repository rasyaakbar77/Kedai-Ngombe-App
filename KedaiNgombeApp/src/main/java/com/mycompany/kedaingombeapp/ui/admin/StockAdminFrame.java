    private void siapkanTabel() {
        tableModel = new DefaultTableModel(
            new Object[]{"ID", "Nama", "Kategori", "Harga", "Stok"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;   // tabel cuma buat dilihat, edit lewat form
            }
        };
        tblMenu.setModel(tableModel);
        tblMenu.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);

        // Klik baris -> isi form
        tblMenu.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) isiFormDariBaris();
        });
    }

    private void siapkanKategori() {
        cmbKategori.removeAllItems();
        for (String k : Menu.KATEGORI) {
            cmbKategori.addItem(k);
        }
    }

    private void muatTabel() {
        tableModel.setRowCount(0);
        List<Menu> list = menuService.getAll();
        for (Menu m : list) {
            tableModel.addRow(new Object[]{
                m.getId(), m.getNama(), m.getKategori(), m.getHarga(), m.getStok()
            });
        }
    }

    private void isiFormDariBaris() {
        int row = tblMenu.getSelectedRow();
        if (row < 0) return;

        idTerpilih = (int) tableModel.getValueAt(row, 0);
        txtNama.setText(tableModel.getValueAt(row, 1).toString());
        cmbKategori.setSelectedItem(tableModel.getValueAt(row, 2).toString());
        txtHarga.setText(tableModel.getValueAt(row, 3).toString());
        txtStok.setText(tableModel.getValueAt(row, 4).toString());
    }

    private void resetForm() {
        idTerpilih = -1;
        txtNama.setText("");
        txtHarga.setText("");
        txtStok.setText("");
        cmbKategori.setSelectedIndex(0);
        tblMenu.clearSelection();
    }

    // Baca isi form jadi objek Menu, balikin null kalau input salah
    private Menu bacaForm() {
        String nama = txtNama.getText().trim();
        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama menu wajib diisi");
            return null;
        }

        int harga, stok;
        try {
            harga = Integer.parseInt(txtHarga.getText().trim());
            stok = Integer.parseInt(txtStok.getText().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Harga dan stok harus berupa angka");
            return null;
        }
        if (harga <= 0 || stok < 0) {
            JOptionPane.showMessageDialog(this, "Harga harus lebih dari 0 dan stok tidak boleh negatif");
            return null;
        }

        Menu m = new Menu();
        m.setNama(nama);
        m.setKategori(cmbKategori.getSelectedItem().toString());
        m.setHarga(harga);
        m.setStok(stok);
        m.setGambar("images/Chocolate_Milk_Tea.jpg");   // placeholder dulu
        return m;
    }
