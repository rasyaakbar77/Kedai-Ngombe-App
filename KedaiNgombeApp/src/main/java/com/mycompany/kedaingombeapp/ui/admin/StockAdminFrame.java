    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // TODO add your handling code here:
        Menu m = bacaForm();
        if (m == null) return;

        if (menuService.insert(m)) {
            JOptionPane.showMessageDialog(this, "Menu berhasil ditambah");
            muatTabel();
            resetForm();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menambah menu");
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        if (idTerpilih < 0) {
        JOptionPane.showMessageDialog(this, "Pilih menu di tabel dulu");
        return;
        }
        Menu m = bacaForm();
        if (m == null) return;
        m.setId(idTerpilih);

        if (menuService.update(m)) {
            JOptionPane.showMessageDialog(this, "Menu berhasil diubah");
            muatTabel();
            resetForm();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal mengubah menu");
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        if (idTerpilih < 0) {
        JOptionPane.showMessageDialog(this, "Pilih menu di tabel dulu");
        return;
        }
        int konfirmasi = JOptionPane.showConfirmDialog(this,
            "Yakin hapus menu ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (konfirmasi != JOptionPane.YES_OPTION) return;

        if (menuService.delete(idTerpilih)) {
            muatTabel();
            resetForm();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menghapus menu");
        }
    }//GEN-LAST:event_btnHapusActionPerformed

